#!/usr/bin/env node
// Emit SQL that seeds a realistic SLOVO progress state for store screenshots.
//
// Reads the bundled content so lesson and card ids can never drift from the app.
// Everything is deterministic: same content in, same numbers out.
//
//   node scripts/gen-seed-sql.mjs > build/seed.sql
//
// stdout = SQL, stderr = a human summary to check against the app's YOU screen.

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT = join(ROOT, "composeApp/src/commonMain/composeResources/files/content");

// Must match SrsScheduler.INTERVALS — review interval in days, indexed by box.
const INTERVALS = [1, 2, 4, 7, 14, 30];
// Cards per box, index = box 0..5. Sums to the number of seen cards.
const BOX_COUNTS = [6, 8, 10, 12, 11, 8];
const COMPLETED_UNITS = 4; // units 1-4 => the first 12 lessons
const XP = 1240;
const STREAK = 9;

// todayEpochDay() is LOCAL days since the epoch on both platforms
// (LocalDate.now().toEpochDay() on Android, timezone-adjusted NSDate on iOS),
// so shift by the local offset before dividing.
const now = new Date();
const TODAY = Math.floor((now.getTime() - now.getTimezoneOffset() * 60_000) / 86_400_000);

const manifest = JSON.parse(readFileSync(join(CONTENT, "manifest.json"), "utf8"));
const units = manifest.units.map((u) => ({
  ...u,
  ...JSON.parse(readFileSync(join(CONTENT, `${u.id}.json`), "utf8")),
}));

// One flat lesson sequence, in the order HomeScreen renders and unlocks them.
const lessons = units.flatMap((u) => u.lessons);
const completedCount = units
  .slice(0, COMPLETED_UNITS)
  .reduce((n, u) => n + u.lessons.length, 0);
const completed = lessons.slice(0, completedCount);
const partial = lessons.slice(completedCount, completedCount + 1); // studied, not finished

// Cards of every completed lesson, then of the partially-studied one.
const seenIds = [...completed, ...partial].flatMap((l) => l.cardIds);

// Boxes descending: the earliest-learned cards sit in the highest box.
const boxes = [];
for (let b = BOX_COUNTS.length - 1; b >= 0; b--) {
  for (let k = 0; k < BOX_COUNTS[b]; k++) boxes.push(b);
}
if (boxes.length !== seenIds.length) {
  throw new Error(
    `BOX_COUNTS sums to ${boxes.length} but ${seenIds.length} cards are seen — adjust BOX_COUNTS`,
  );
}

const cards = seenIds.map((id, i) => {
  const box = boxes[i];
  const interval = INTERVALS[box];
  const due = i % 4 === 0; // 14 of 55
  // dueDay = lastSeen + interval. Due cards land on or before today (overdue by
  // 0-2 days); the rest land 1..6 days out so the 7-day forecast chart is full.
  const lastSeen = due
    ? TODAY - interval - (i % 3)
    : TODAY - interval + (1 + (i % Math.min(6, interval)));
  return { id, box, lastSeen, correct: box + 1, wrong: i % 2 === 0 ? 1 : 0, due };
});

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const out = [];
out.push("-- Generated by scripts/gen-seed-sql.mjs — screenshot seed state.");
out.push(`-- today (local epoch day) = ${TODAY}`);
out.push("BEGIN TRANSACTION;");
out.push("DELETE FROM card_progress;");
out.push("DELETE FROM lesson_progress;");
out.push("DELETE FROM user_stats;");
out.push(
  `INSERT INTO user_stats(id, xp, streak_days, last_active_day) VALUES (0, ${XP}, ${STREAK}, ${TODAY});`,
);
completed.forEach((l, n) => {
  const lastSeen = TODAY - (completed.length - 1 - n);
  out.push(
    `INSERT INTO lesson_progress(lesson_id, completed, best_correct, last_seen) ` +
      `VALUES (${q(l.id)}, 1, ${l.cardIds.length}, ${lastSeen});`,
  );
});
cards.forEach((c) => {
  out.push(
    `INSERT INTO card_progress(card_id, seen, correct, wrong, last_seen, box) ` +
      `VALUES (${q(c.id)}, 1, ${c.correct}, ${c.wrong}, ${c.lastSeen}, ${c.box});`,
  );
});
out.push("COMMIT;");
process.stdout.write(out.join("\n") + "\n");

const correct = cards.reduce((n, c) => n + c.correct, 0);
const wrong = cards.reduce((n, c) => n + c.wrong, 0);
const dueToday = cards.filter((c) => c.due).length;
const histogram = BOX_COUNTS.map(
  (_, b) => cards.filter((c) => c.box === b).length,
);
const forecast = Array.from({ length: 7 }, (_, d) =>
  cards.filter((c) => Math.max(0, c.lastSeen + INTERVALS[c.box] - TODAY) === d).length,
);
console.error(
  [
    `today (local epoch day) : ${TODAY}`,
    `lessons completed       : ${completed.length} of ${lessons.length}`,
    `partially studied       : ${partial.map((l) => l.id).join(", ")}`,
    `cards seen              : ${cards.length}`,
    `cards mastered          : ${cards.filter((c) => c.correct > 0).length}`,
    `due today               : ${dueToday}`,
    `box histogram (0..5)    : ${histogram.join(", ")}`,
    `7-day forecast (d0..d6) : ${forecast.join(", ")}`,
    `answers                 : ${correct + wrong} (${correct} correct, ${wrong} wrong)`,
    `accuracy                : ${Math.round((correct / (correct + wrong)) * 100)}%`,
    `xp / streak             : ${XP} / ${STREAK}`,
  ].join("\n") + "\n",
);
